"""Procurement and Production view for MedChain AI.

Workflow Step 4:
- Guided 5-step workflow stepper.
- Procurement KPIs with top accents and status pills.
- Purchase recommendations table (read-only).
- Supplier capability matrix with material filter.
- Mathematical procurement linear optimization form (budget, max lead time, MOQ).
- Infeasible constraint alert handling.
- Production schedule before and after table.
- 'Next step' button routing to Governance and approval.
"""

from __future__ import annotations

from typing import Any, Dict, Optional
import pandas as pd
import streamlit as st
from frontend.components.kpi_cards import render_procurement_kpis
from frontend.components.status_components import (
    render_empty_state,
    render_error_notice,
    render_status_pill,
    render_workflow_bar,
)
from frontend.components.tables import render_table
from frontend.data_access import run_optimisation


def render(results: Optional[Dict[str, Any]]) -> None:
    """Render the Procurement and production workflow page."""
    # 1. Top Guided Stepper
    pipeline_state = results.get("pipeline") if results else None
    render_workflow_bar(pipeline_stages=pipeline_state, current_page_index=4)

    st.markdown(
        """
        <div style="margin-bottom: 20px;">
            <div style="font-size: 11px; font-weight: 700; color: #0284C7; text-transform: uppercase; letter-spacing: 0.05em; margin-bottom: 2px;">
                Workflow Step 4 of 5
            </div>
            <h1 style="font-size: 20px; font-weight: 800; color: #0F172A; margin: 0; letter-spacing: -0.02em;">
                Procurement Optimization and Schedule Alignment
            </h1>
            <div style="color: #64748B; font-size: 13px; margin-top: 4px;">
                Mixed-integer linear programming for multi-supplier PO allocation and batch rescheduling
            </div>
        </div>
        """,
        unsafe_allow_html=True,
    )

    # Empty state check
    if not results or not any(results.get("kpis", {}).values()):
        render_empty_state("No results yet. Run analysis from Overview.")
        st.button("Next step: Governance and approval", disabled=True, key="next_step_disabled_procurement")
        return

    # 2. Procurement KPIs
    proc_kpis = results.get("proc_kpis", {})
    render_procurement_kpis(proc_kpis)

    st.markdown('<div style="margin-top: 24px;"></div>', unsafe_allow_html=True)

    # 3. Purchase Recommendations Table (Read-Only)
    proc_df = results.get("procurement", pd.DataFrame())
    render_table(
        proc_df,
        title="Purchase order recommendations (Read-only reference)",
        empty_message="No purchase recommendations generated by the pipeline.",
        download_filename="purchase_recommendations.csv",
    )

    st.markdown('<div style="margin-top: 24px;"></div>', unsafe_allow_html=True)

    # 4. Supplier Comparison Table with Material Filter
    suppliers_df = results.get("suppliers", pd.DataFrame())
    materials_df = results.get("inventory", pd.DataFrame())

    mat_options = ["All materials"]
    if isinstance(materials_df, pd.DataFrame) and not materials_df.empty:
        col_m = "material" if "material" in materials_df.columns else materials_df.columns[0]
        mat_options.extend(materials_df[col_m].dropna().unique().tolist())

    s_col, _ = st.columns([4, 6])
    with s_col:
        selected_mat = st.selectbox("Filter suppliers by material capability", options=mat_options, key="proc_mat_filter")

    filtered_suppliers = suppliers_df.copy() if isinstance(suppliers_df, pd.DataFrame) else pd.DataFrame()
    if selected_mat != "All materials" and not filtered_suppliers.empty and "materials" in filtered_suppliers.columns:
        filtered_suppliers = filtered_suppliers[
            filtered_suppliers["materials"].astype(str).str.contains(selected_mat, case=False, na=False)
        ]

    render_table(
        filtered_suppliers,
        title="Supplier evaluation matrix: reliability and qualification",
        empty_message="No supplier records match the selected material.",
        download_filename="supplier_evaluation_matrix.csv",
    )

    st.markdown('<div style="margin-top: 28px;"></div>', unsafe_allow_html=True)

    # 5. Optimization Form
    st.markdown(
        '<div style="font-size: 14px; font-weight: 700; color: #0F172A; text-transform: uppercase; '
        'letter-spacing: 0.04em; margin: 16px 0 8px 0;">Mathematical Purchase Allocation Optimization</div>',
        unsafe_allow_html=True,
    )

    with st.form("procurement_optimization_form"):
        f_col1, f_col2, f_col3 = st.columns(3)
        with f_col1:
            budget_val = st.number_input("Maximum procurement budget ($)", min_value=1000.0, max_value=10000000.0, value=250000.0, step=10000.0)
        with f_col2:
            max_lead_time_val = st.number_input("Maximum permissible lead time (days)", min_value=1, max_value=180, value=45, step=5)
        with f_col3:
            st.markdown('<div style="margin-top: 28px;"></div>', unsafe_allow_html=True)
            apply_moq_val = st.checkbox("Enforce minimum order quantities (MOQ)", value=True)

        opt_submitted = st.form_submit_button("Run mathematical optimization", type="primary")

    if opt_submitted:
        with st.spinner("Solving multi-echelon procurement optimization model..."):
            opt_result, err = run_optimisation(
                budget=budget_val,
                max_lead_time=max_lead_time_val,
                apply_moq=apply_moq_val,
            )
            if err:
                render_error_notice(f"Optimisation notice: {err}")
            elif isinstance(opt_result, dict):
                st.session_state["optimisation_result"] = opt_result
                st.rerun()

    # Display Optimization Results if present
    opt_data = st.session_state.get("optimisation_result")
    if opt_data and isinstance(opt_data, dict):
        status = opt_data.get("status", "Unknown")
        total_cost = opt_data.get("total_cost")
        budget_use = opt_data.get("budget_use")
        allocation_df = opt_data.get("allocation", pd.DataFrame())

        if str(status).upper() == "INFEASIBLE":
            st.markdown(
                """
                <div style="background-color: #FEF2F2; border: 1px solid #FECACA; border-left: 4px solid #DC2626;
                            border-radius: 8px; padding: 16px; margin: 16px 0;">
                    <div style="color: #991B1B; font-weight: 700; font-size: 14px; text-transform: uppercase;">
                        Model Status: Infeasible Solution
                    </div>
                    <div style="color: #0F172A; font-size: 13px; margin-top: 4px; line-height: 1.4;">
                        No viable allocation satisfies all constraints simultaneously under the current budget ceiling and lead-time window.
                        Adjust budget parameters or relax lead-time criteria to reach feasibility.
                    </div>
                </div>
                """,
                unsafe_allow_html=True,
            )
        else:
            status_pill = render_status_pill(status)
            cost_str = f"${total_cost:,.2f}" if isinstance(total_cost, (int, float)) else str(total_cost)
            use_str = f"{budget_use * 100:.1f}%" if isinstance(budget_use, (int, float)) else str(budget_use)

            st.markdown(
                f"""
                <div style="background-color: #FFFFFF; border: 1px solid #E2E8F0; border-radius: 8px;
                            box-shadow: 0 1px 3px 0 rgba(15, 23, 42, 0.05); padding: 14px 18px; margin: 16px 0;">
                    <div style="display: flex; align-items: center; justify-content: space-between;">
                        <div style="display: flex; align-items: center; gap: 12px;">
                            <span style="font-size: 13px; font-weight: 700; color: #0F172A;">Optimization Outcome</span>
                            {status_pill}
                        </div>
                        <div style="font-size: 13px; color: #334155;">
                            Allocated Spend: <b>{cost_str}</b> &nbsp;|&nbsp; Budget Utilization: <b>{use_str}</b>
                        </div>
                    </div>
                </div>
                """,
                unsafe_allow_html=True,
            )

            render_table(
                allocation_df,
                title="Optimal purchase order allocation across qualified vendors",
                download_filename="optimal_procurement_allocation.csv",
            )

    st.markdown('<div style="margin-top: 28px;"></div>', unsafe_allow_html=True)

    # 6. Production Schedule Before and After
    schedule_df = results.get("schedule", pd.DataFrame())
    render_table(
        schedule_df,
        title="Manufacturing batch schedules (Planned baseline vs recovery adjusted)",
        empty_message="No production order schedules reported by backend.",
        download_filename="production_schedule.csv",
    )

    # Footer Navigation: Next Step button
    st.markdown('<div style="margin-top: 36px; border-top: 1px solid #E2E8F0; padding-top: 18px;"></div>', unsafe_allow_html=True)
    col_dummy, col_next = st.columns([7, 3])
    with col_next:
        if st.button("Next step: Governance and approval", type="primary", use_container_width=True, key="btn_next_step_procurement"):
            st.session_state["page"] = "5. Approval"
            st.rerun()
